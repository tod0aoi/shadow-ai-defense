import { v4 as uuidv4 } from 'uuid';
import { db } from '../config/database';
import { PolicySeverity } from '../types';
import { DetectionResult } from './detection.service';
import { EvaluatedViolation } from './policy.engine';
import { logAuditEvent } from '../middleware/audit';

export class IncidentService {
  /**
   * Evaluates if event warrants incident creation and generates SOC incident ticket.
   */
  async evaluateAndCreateIncident(params: {
    eventId: string;
    userId?: string;
    serviceName: string;
    riskScore: number;
    severity: PolicySeverity;
    detectionResult: DetectionResult;
    violations: EvaluatedViolation[];
  }): Promise<{ incidentCreated: boolean; incidentId?: string }> {
    const { eventId, userId, serviceName, riskScore, severity, detectionResult, violations } = params;

    // Trigger incident if severity is HIGH or CRITICAL, or risk score >= 60
    const shouldCreate = riskScore >= 60 || severity === 'HIGH' || severity === 'CRITICAL';
    if (!shouldCreate) {
      return { incidentCreated: false };
    }

    const incidentId = uuidv4();
    const primaryFindings = detectionResult.detections.map((d) => d.subcategory).slice(0, 3).join(', ');
    const title = `[${severity}] Shadow AI Data Exfiltration: ${primaryFindings || 'Sensitive Data'} via ${serviceName}`;

    // Auto-generate preliminary deterministic summary
    const preliminarySummary = 
      `Automated Detection Alert: User submitted sensitive organizational data (${primaryFindings}) ` +
      `to external AI service "${serviceName}". Calculated risk score: ${riskScore}/100 (${severity}). ` +
      `Matched ${violations.length} corporate security policy violations.`;

    const preliminaryRemediation = 
      `1. Review masked evidence in event record.\n` +
      `2. Contact user to confirm business justification or inadvertent submission.\n` +
      `3. If credentials or keys were exposed, immediately rotate affected secrets in cloud console.\n` +
      `4. Verify whether external AI service retains conversation history for training.`;

    // Persist incident
    await db.execute(
      `INSERT INTO incidents (id, event_id, title, severity, risk_score, status, ai_summary, ai_remediation)
       VALUES ($1, $2, $3, $4, $5, $6, $7, $8)`,
      [
        incidentId,
        eventId,
        title,
        severity,
        riskScore,
        'OPEN',
        preliminarySummary,
        preliminaryRemediation,
      ]
    );

    // Insert initial incident timeline entry
    const timelineId = uuidv4();
    await db.execute(
      `INSERT INTO incident_timeline (id, incident_id, actor_id, action, notes)
       VALUES ($1, $2, $3, $4, $5)`,
      [
        timelineId,
        incidentId,
        userId || null,
        'INCIDENT_AUTOMATICALLY_GENERATED',
        `Incident generated by Risk Engine with score ${riskScore} (${severity})`,
      ]
    );

    // Audit log
    await logAuditEvent({
      actor_id: userId,
      action: 'INCIDENT_CREATED',
      target_entity: 'incidents',
      target_id: incidentId,
      details: { riskScore, severity, serviceName, findings: primaryFindings },
    });

    return { incidentCreated: true, incidentId };
  }
}

export const incidentService = new IncidentService();
