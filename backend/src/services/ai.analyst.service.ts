import path from 'path';
import { spawn } from 'child_process';
import { v4 as uuidv4 } from 'uuid';
import { db } from '../config/database';

export interface AIAnalysisResult {
  incident_summary: string;
  threat_actor_perspective: string;
  potential_impact: string;
  investigation_steps: string[];
  remediation_runbook: string[];
  engine: string;
}

export async function runAIIncidentAnalysis(incidentId: string): Promise<AIAnalysisResult> {
  // 1. Fetch incident record
  const incident = await db.queryOne(
    `SELECT i.*, e.redacted_payload, s.name as service_name
     FROM incidents i
     JOIN events e ON i.event_id = e.id
     JOIN ai_services s ON e.ai_service_id = s.id
     WHERE i.id = $1`,
    [incidentId]
  );

  if (!incident) {
    throw new Error(`Incident ${incidentId} not found`);
  }

  // 2. Fetch detections (masked evidence)
  const detections = await db.query(
    'SELECT category, subcategory, evidence_masked FROM detections WHERE event_id = $1',
    [incident.event_id]
  );

  // 3. Fetch matched policies
  const violations = await db.query(
    `SELECT p.name as policy_name, pv.severity 
     FROM policy_violations pv 
     JOIN policies p ON pv.policy_id = p.id 
     WHERE pv.event_id = $1`,
    [incident.event_id]
  );

  // 4. Construct sanitized context (ZERO raw secrets, strictly masked)
  const sanitizedContext = {
    service_name: incident.service_name,
    risk_score: incident.risk_score,
    severity: incident.severity,
    categories: Array.from(new Set(detections.map((d: any) => d.category))),
    masked_evidence: detections.map((d: any) => `${d.subcategory}: ${d.evidence_masked}`),
    violated_policies: violations.map((v: any) => v.policy_name),
    redacted_payload: incident.redacted_payload,
  };

  // 5. Execute python AI analyst engine
  const scriptPath = path.resolve(__dirname, '../../../ai-engine/analyst.py');
  const pythonExe = process.platform === 'win32' ? 'python' : 'python3';

  const analysis: AIAnalysisResult = await new Promise((resolve, reject) => {
    const child = spawn(pythonExe, [scriptPath], { windowsHide: true });
    let stdout = '';
    let stderr = '';

    child.stdout.on('data', (d) => (stdout += d));
    child.stderr.on('data', (d) => (stderr += d));

    child.on('close', (code) => {
      if (code === 0) {
        try {
          resolve(JSON.parse(stdout));
        } catch (e) {
          reject(new Error(`Failed to parse AI analyst output: ${stdout}`));
        }
      } else {
        reject(new Error(`AI analyst failed with code ${code}: ${stderr}`));
      }
    });

    child.on('error', reject);

    child.stdin.write(JSON.stringify(sanitizedContext));
    child.stdin.end();
  });

  // 6. Update incident in database
  const formattedSummary = 
    `${analysis.incident_summary}\n\n` +
    `[THREAT PERSPECTIVE]: ${analysis.threat_actor_perspective}\n\n` +
    `[POTENTIAL IMPACT]: ${analysis.potential_impact}`;

  const formattedRemediation = 
    `INVESTIGATION PROTOCOL:\n${analysis.investigation_steps.map((s, i) => `${i + 1}. ${s}`).join('\n')}\n\n` +
    `REMEDIATION RUNBOOK:\n${analysis.remediation_runbook.map((r, i) => `${i + 1}. ${r}`).join('\n')}\n\n` +
    `[ANALYSIS ENGINE]: ${analysis.engine}`;

  await db.execute(
    `UPDATE incidents 
     SET ai_summary = $1, ai_remediation = $2, updated_at = CURRENT_TIMESTAMP 
     WHERE id = $3`,
    [formattedSummary, formattedRemediation, incidentId]
  );

  // 7. Add timeline entry
  const timelineId = uuidv4();
  await db.execute(
    `INSERT INTO incident_timeline (id, incident_id, action, notes)
     VALUES ($1, $2, $3, $4)`,
    [
      timelineId,
      incidentId,
      'AI_ANALYSIS_COMPLETED',
      `Triage advisory generated by ${analysis.engine}`,
    ]
  );

  return analysis;
}
